from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
import shutil


@dataclass(frozen=True, slots=True)
class BenchmarkPackLayout:
    root: Path
    images_dir: Path
    gt_dir: Path
    manifest_path: Path
    plan_path: Path


PRESERVATION_CATEGORIES = (
    "identity",
    "appearance_change",
    "day_night",
    "repetitive_facade",
    "occlusion",
    "sparse_facade",
    "technical_transform",
)

ALL_CATEGORIES = PRESERVATION_CATEGORIES + (
    "camera_mismatch",
    "geometry_change",
)


def _safe_copy(source: Path, destination: Path, *, force: bool) -> None:
    if destination.exists() and not force:
        raise FileExistsError(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)


def _gt_template() -> dict:
    return {
        "schema_version": "0.1",
        "reference_regions": [],
        "after_regions": [],
        "_instructions": [
            "Add at least 10 stable matching IDs for repetitive-facade benchmark.",
            "Use the same semantic IDs in BEFORE and AFTER, e.g. W001, W002.",
            "Each polygon_xy needs at least 3 [x, y] points.",
            "Do not generate GT from the feature provider being evaluated.",
        ],
    }


def initialize_benchmark_pack(
    output_dir: str | Path,
    *,
    reference_image: str | Path,
    evaluation_reference_image: str | Path | None = None,
    dataset_id: str = "ARCHVIZ_QC_PACK_001",
    force: bool = False,
) -> BenchmarkPackLayout:
    root = Path(output_dir)
    images_dir = root / "images"
    gt_dir = root / "gt"
    manifest_path = root / "manifest.json"
    plan_path = root / "PACK_PLAN.md"

    reference = Path(reference_image)
    if not reference.exists():
        raise FileNotFoundError(reference)

    eval_reference = (
        None if evaluation_reference_image is None
        else Path(evaluation_reference_image)
    )
    if eval_reference is not None and not eval_reference.exists():
        raise FileNotFoundError(eval_reference)

    root.mkdir(parents=True, exist_ok=True)
    images_dir.mkdir(parents=True, exist_ok=True)
    gt_dir.mkdir(parents=True, exist_ok=True)

    dev_name = f"reference_dev{reference.suffix.lower() or '.png'}"
    dev_dest = images_dir / dev_name
    _safe_copy(reference, dev_dest, force=force)

    eval_name = None
    if eval_reference is not None:
        eval_name = f"reference_eval{eval_reference.suffix.lower() or '.png'}"
        _safe_copy(eval_reference, images_dir / eval_name, force=force)

    if manifest_path.exists() and not force:
        raise FileExistsError(manifest_path)

    cases = [
        {
            "case_id": "identity_01::dev",
            "category": "identity",
            "reference_path": f"images/{dev_name}",
            "after_path": f"images/{dev_name}",
            "expected_geometry_change": False,
            "notes": "Identity control generated by pack initializer.",
        }
    ]

    if eval_name is not None:
        cases.append(
            {
                "case_id": "identity_02::eval",
                "category": "identity",
                "reference_path": f"images/{eval_name}",
                "after_path": f"images/{eval_name}",
                "expected_geometry_change": False,
                "notes": "Evaluation identity control generated by pack initializer.",
            }
        )

    manifest = {
        "schema_version": "0.1",
        "dataset_id": dataset_id,
        "cases": cases,
    }
    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    for split in ("dev", "eval"):
        gt_path = gt_dir / f"repetitive_{split}.template.json"
        if gt_path.exists() and not force:
            continue
        gt_path.write_text(
            json.dumps(_gt_template(), indent=2, ensure_ascii=False),
            encoding="utf-8",
        )

    plan_lines = [
        f"# {dataset_id} — preparation plan",
        "",
        "The pack starts intentionally incomplete. Add real variants first, then run readiness.",
        "",
        "## Current source references",
        f"- DEV reference: images/{dev_name}",
        f"- EVAL reference: {'images/' + eval_name if eval_name else 'NOT PROVIDED'}",
        "",
        "## Required pair families",
    ]
    for category in ALL_CATEGORIES:
        plan_lines.append(f"- [ ] {category} ::dev")
        plan_lines.append(f"- [ ] {category} ::eval")

    plan_lines += [
        "",
        "## Repetitive-facade semantic GT",
        "- [ ] Fill gt/repetitive_dev.template.json with >=10 stable common IDs",
        "- [ ] Fill gt/repetitive_eval.template.json with >=10 stable common IDs",
        "",
        "## Suggested first geometry edits",
        "- [ ] move one opening",
        "- [ ] widen one opening",
        "- [ ] remove one opening",
        "",
        "## Gate order",
        "1. Add cases to manifest.json.",
        "2. Run scripts/check_benchmark_readiness.py.",
        "3. Fix all errors and review warnings.",
        "4. Freeze the pack with scripts/freeze_benchmark_dataset.py.",
        "5. Only then run/tune feature-provider benchmarks.",
        "",
    ]
    plan_path.write_text("\n".join(plan_lines), encoding="utf-8")

    return BenchmarkPackLayout(
        root=root,
        images_dir=images_dir,
        gt_dir=gt_dir,
        manifest_path=manifest_path,
        plan_path=plan_path,
    )
